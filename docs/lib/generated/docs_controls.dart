/// The editable kind of one playground control.
enum ControlKind {
  /// On/off switch (`bool`).
  toggle,

  /// One-of-many (`enum`, options carry the value names).
  select,

  /// Free text (`String`, or a text-like `Widget` slot).
  text,

  /// Bounded number (`int`/`double`).
  slider,

  /// Theme colour (`Color`, options carry token names).
  colorToken,

  /// Shared press toggle (null vs no-op callbacks).
  enabled,

  /// Shown but not editable (`readOnlyReason` says why).
  readOnly,
}

/// One playground control of one component.
class ControlSpec {
  /// Creates a control spec.
  const ControlSpec({
    required this.name,
    required this.label,
    required this.kind,
    required this.type,
    required this.isRequired,
    this.defaultValue,
    this.options = const <String>[],
    this.min,
    this.max,
    this.step,
    this.isInt = false,
    this.isBuilder = false,
    this.readOnlyReason,
  });

  /// Parameter name (`variant`, or `enabled`).
  final String name;

  /// Human label (`Variant`).
  final String label;

  /// Editable kind.
  final ControlKind kind;

  /// Declared type (`ButtonVariant`).
  final String type;

  /// Whether the parameter is required (always emitted).
  final bool isRequired;

  /// Default in Dart-source shape, or null when unknown.
  final String? defaultValue;

  /// Select values or theme token names.
  final List<String> options;

  /// Slider lower bound (null unless `slider`).
  final double? min;

  /// Slider upper bound.
  final double? max;

  /// Slider step, or null for the kind default.
  final double? step;

  /// Whether the slider value is an int.
  final bool isInt;

  /// Whether a text control renders inside a builder closure.
  final bool isBuilder;

  /// Why a read-only row cannot be edited.
  final String? readOnlyReason;

  /// Whether the panel can edit this control.
  bool get isEditable => kind != ControlKind.readOnly;
}

