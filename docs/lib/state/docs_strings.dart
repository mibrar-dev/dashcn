/// Reads one chrome string for [locale] (English fallback).
String docsChrome(Locale locale, String key) {
  final String tag = docsLocaleTag(locale);
  final Map<String, String>? table = _values[tag];
  final String? value = table?[key];
  if (value != null) {
    return value;
  }
  return _values['en']![key] ?? key;
}

/// Replaces `{count}` / `{command}` placeholders in [template].
String docsFill(String template, {int? count, String? command}) {
  var out = template;
  if (count != null) {
    out = out.replaceAll('{count}', '$count');
  }
  if (command != null) {
    out = out.replaceAll('{command}', command);
  }
  return out;
}

/// Localized file-count badge label (`1 file`, `4 files`).
String docsFileCount(int count, Locale locale) {
  if (count == 1) {
    return docsChrome(locale, 'fileOne');
  }
  return docsFill(docsChrome(locale, 'fileMany'), count: count);
}

