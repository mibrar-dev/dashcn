/// Locale tag used as the [_values] map key (`en`, `de`, `ar`, `zh_Hant`,
/// `zh_Hans`, `pt_BR`, …).
String docsLocaleTag(Locale locale) {
  final StringBuffer tag = StringBuffer(locale.languageCode);
  if (locale.scriptCode != null && locale.scriptCode!.isNotEmpty) {
    tag.write('_${locale.scriptCode}');
  }
  if (locale.countryCode != null && locale.countryCode!.isNotEmpty) {
    tag.write('_${locale.countryCode}');
  }
  return tag.toString();
}

/// Parses a [docsLocaleTag] back into a [Locale].
Locale docsLocaleFromTag(String tag) {
  final List<String> parts = tag.split('_');
  if (parts.length == 1) {
    return Locale(parts[0]);
  }
  if (parts.length == 2) {
    // `zh_Hant` / `zh_Hans` are script codes; `pt_BR` is a country code.
    if (parts[0] == 'zh' && (parts[1] == 'Hant' || parts[1] == 'Hans')) {
      return Locale.fromSubtags(languageCode: parts[0], scriptCode: parts[1]);
    }
    if (parts[1].length == 2 && parts[1] == parts[1].toUpperCase()) {
      return Locale(parts[0], parts[1]);
    }
    return Locale.fromSubtags(languageCode: parts[0], scriptCode: parts[1]);
  }
  if (parts.length == 3) {
    return Locale.fromSubtags(
      languageCode: parts[0],
      scriptCode: parts[1],
      countryCode: parts[2],
    );
  }
  return Locale(parts[0]);
}

