// gen_sample_strings.dart — builds the preview sample-string table from the
// JSON sources in docs/i18n/samples/.
//
// Source of truth:
//   docs/i18n/samples/en.json      every sample key (English key -> English text)
//   docs/i18n/samples/<tag>.json   one file per locale (key -> translation); a
//                                  missing key falls back to English at runtime
//
// Output:
//   docs/lib/generated/docs_sample_table.dart
//
// Usage (from docs/):
//   dart run tool/gen_sample_strings.dart           # write the table + print the report
//   dart run tool/gen_sample_strings.dart --check   # exit 1 when the table is stale or a locale has unknown keys
//
// Adding a locale batch means editing only the locale's JSON file and re-running
// this script. Keys are never invented here: a locale key that is not in en.json
// is an error.

import 'dart:convert';
import 'dart:io';

const String _samplesDir = 'i18n/samples';
const String _outPath = 'lib/generated/docs_sample_table.dart';

void main(List<String> args) {
  final bool check = args.contains('--check');
  final Map<String, String> english = _readMap(File('$_samplesDir/en.json'));
  final List<String> keys = english.keys.toList()..sort();

  final List<String> tags =
      Directory(_samplesDir)
          .listSync()
          .whereType<File>()
          .map((File f) => f.uri.pathSegments.last)
          .where((String name) => name.endsWith('.json') && name != 'en.json')
          .map((String name) => name.substring(0, name.length - '.json'.length))
          .toList()
        ..sort();

  final List<String> errors = <String>[];
  final Map<String, Map<String, String>> tables =
      <String, Map<String, String>>{};
  for (final String tag in tags) {
    final Map<String, String> table = _readMap(File('$_samplesDir/$tag.json'));
    for (final MapEntry<String, String> entry in table.entries) {
      if (!english.containsKey(entry.key)) {
        errors.add('$tag.json: unknown key "${entry.key}" (not in en.json)');
      }
      if (entry.value.trim().isEmpty) {
        errors.add('$tag.json: empty translation for "${entry.key}"');
      }
    }
    tables[tag] = table;
  }

  _printReport(keys, tags, tables);

  final String output = _formatted(_render(tags, tables));
  if (errors.isNotEmpty) {
    stderr.writeln(errors.join('\n'));
    exitCode = 1;
    return;
  }
  final File out = File(_outPath);
  if (check) {
    if (!out.existsSync() || out.readAsStringSync() != output) {
      stderr.writeln(
        '$_outPath is stale: run dart run tool/gen_sample_strings.dart',
      );
      exitCode = 1;
    }
    return;
  }
  out.writeAsStringSync(output);
  stdout.writeln('wrote $_outPath');
}

/// [source] as `dart format` writes it, so `--check` and the CI format step agree.
String _formatted(String source) {
  // Inside the package so dart format picks the package's language version.
  final File file = File('tool/.docs_sample_table.tmp.dart')
    ..writeAsStringSync(source);
  try {
    final ProcessResult result = Process.runSync('dart', <String>[
      'format',
      file.path,
    ]);
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return file.readAsStringSync();
  } finally {
    file.deleteSync();
  }
}

Map<String, String> _readMap(File file) {
  final Object? decoded = jsonDecode(file.readAsStringSync());
  if (decoded is! Map) {
    throw FormatException('${file.path} must be a JSON object');
  }
  return decoded.map(
    (Object? k, Object? v) => MapEntry(k as String, v as String),
  );
}

void _printReport(
  List<String> keys,
  List<String> tags,
  Map<String, Map<String, String>> tables,
) {
  stdout.writeln('Sample-string coverage (${keys.length} keys in en.json)');
  stdout.writeln(
    '${'locale'.padRight(10)}${'translated'.padLeft(12)}${'fallback'.padLeft(10)}',
  );
  int complete = 0;
  for (final String tag in tags) {
    final Map<String, String> table = tables[tag] ?? <String, String>{};
    final int translated = keys.where(table.containsKey).length;
    final int fallback = keys.length - translated;
    if (fallback == 0) {
      complete++;
    }
    stdout.writeln(
      '${tag.padRight(10)}${'$translated/${keys.length}'.padLeft(12)}${fallback.toString().padLeft(10)}',
    );
  }
  stdout.writeln('complete locales: $complete of ${tags.length}');
}

String _render(List<String> tags, Map<String, Map<String, String>> tables) {
  final StringBuffer b = StringBuffer();
  b.writeln(
    '// GENERATED by docs/tool/gen_sample_strings.dart from docs/i18n/samples/.',
  );
  b.writeln(
    '// Do not edit by hand: change the JSON files and re-run the generator.',
  );
  b.writeln();
  b.writeln(
    '/// Translated sample strings per locale tag (see `docsLocaleTag`).',
  );
  b.writeln(
    '/// A locale or key that is missing here falls back to English at runtime.',
  );
  b.writeln('const Map<String, Map<String, String>> docsSampleTable =');
  b.writeln('    <String, Map<String, String>>{');
  for (final String tag in tags) {
    final Map<String, String> table = tables[tag] ?? <String, String>{};
    if (table.isEmpty) {
      continue;
    }
    b.writeln("  '$tag': <String, String>{");
    final List<String> keys = table.keys.toList()..sort();
    for (final String key in keys) {
      b.writeln('    ${_dartString(key)}: ${_dartString(table[key]!)},');
    }
    b.writeln('  },');
  }
  b.writeln('};');
  return b.toString();
}

String _dartString(String value) {
  final String escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}
