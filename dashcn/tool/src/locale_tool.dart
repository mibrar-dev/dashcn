// Offline locale installer for the kit (no network, no new packages).
//
// The single source of truth is the generated
// `lib/src/manifests/locale_tables.json` (built by
// `dart run tool/gen_locale_manifest.dart` from the locale tables): English
// defaults and signatures per key, plus every translated override per
// locale. `locale add` therefore can never invent a locale the kit cannot
// load, and the same JSON ships inside the `dashcn_cli` package for its own
// `locale add`. Pure functions take explicit roots so unit tests run without
// subprocesses.

import 'dart:convert';
import 'dart:io';

/// One shippable locale: the code users type and its text direction.
class LocaleEntry {
  /// Creates a locale entry.
  const LocaleEntry({required this.code, required this.rtl});

  /// Code users type (`ar`, `pt-BR`, `zh-Hans`).
  final String code;

  /// Whether the locale reads right-to-left.
  final bool rtl;

  /// `localizations_<suffix>.dart` holding the table (`pt-BR` -> `pt_br`).
  String get fileSuffix => code.replaceAll('-', '_').toLowerCase();
}

/// Error thrown for usage problems (unknown code, missing project dir).
class LocaleToolError implements Exception {
  /// Creates an error with [message].
  const LocaleToolError(this.message);

  /// Human-readable reason.
  final String message;

  @override
  String toString() => message;
}

/// Locates the kit root (holds `lib/src/manifests/registry.json`) from
/// [start].
Directory? findKitRoot(Directory start) {
  Directory current = start.absolute;
  while (true) {
    if (File('${current.path}/lib/src/manifests/registry.json').existsSync()) {
      return current;
    }
    final Directory parent = current.parent;
    if (parent.path == current.path) {
      return null;
    }
    current = parent;
  }
}

Map<String, Object?> _localeManifest(String kitRoot) {
  final File file = File('$kitRoot/lib/src/manifests/locale_tables.json');
  if (!file.existsSync()) {
    throw const LocaleToolError(
      'locale_tables.json is missing; run tool/gen_locale_manifest.dart',
    );
  }
  final Object? decoded = jsonDecode(file.readAsStringSync());
  if (decoded is! Map<String, Object?>) {
    throw const LocaleToolError('locale_tables.json is corrupt');
  }
  return decoded;
}

/// Every locale the kit ships, in manifest order.
List<LocaleEntry> loadShippableLocales(String kitRoot) {
  final Map<String, Object?> manifest = _localeManifest(kitRoot);
  final Object? locales = manifest['locales'];
  if (locales is! Map) {
    throw const LocaleToolError('locale_tables.json has no locales table');
  }
  final List<LocaleEntry> entries = <LocaleEntry>[];
  for (final MapEntry<Object?, Object?> entry in locales.entries) {
    final String code = entry.key! as String;
    final Object? detail = entry.value;
    if (detail is! Map || detail['direction'] is! String) {
      throw LocaleToolError('locale_tables.json entry "$code" is corrupt');
    }
    // Sanity: the table file the manifest was generated from must exist.
    final String suffix = code.replaceAll('-', '_').toLowerCase();
    final File table = File(
      '$kitRoot/lib/src/primitives/localizations/localizations_$suffix.dart',
    );
    if (!table.existsSync()) {
      throw LocaleToolError('missing table for $code');
    }
    entries.add(LocaleEntry(code: code, rtl: detail['direction'] == 'rtl'));
  }
  return entries;
}

/// Manifest of locales installed into a project (empty when none).
File _manifestFile(String projectDir) =>
    File('$projectDir/dashcn_locales.json');

/// Locales already installed into [projectDir] (empty when none).
List<String> installedLocales(String projectDir) {
  final File manifest = _manifestFile(projectDir);
  if (!manifest.existsSync()) {
    return <String>[];
  }
  final Object? decoded = jsonDecode(manifest.readAsStringSync());
  if (decoded is! Map || decoded['locales'] is! List) {
    throw const LocaleToolError('dashcn_locales.json is corrupt');
  }
  return List<String>.from(decoded['locales'] as List);
}

/// Dart constructor for [code] in the generated wiring file.
String localeConstructor(String code) {
  final List<String> parts = code.split('-');
  if (parts.length == 1) {
    return "const Locale('${parts[0]}')";
  }
  if (parts.length == 2 && parts[1].length == 2) {
    return "const Locale('${parts[0]}', '${parts[1]}')";
  }
  return "Locale.fromSubtags(languageCode: '${parts[0]}', "
      "scriptCode: '${parts[1]}')";
}

/// Renders `lib/dashcn_i18n.dart` for [codes] (sorted, deduplicated).
String renderWiringFile(List<String> codes) {
  final List<String> sorted = codes.toSet().toList()..sort();
  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED by `dart run tool/locale.dart locale add <code>`.')
    ..writeln('// Do not edit by hand: re-run the command (it is idempotent)')
    ..writeln('// to add more locales.')
    ..writeln("import 'package:dashcn/dashcn.dart';")
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln(
      "import 'package:flutter_localizations/flutter_localizations.dart';",
    )
    ..writeln()
    ..writeln('/// Locales installed via `dashcn locale add`.')
    ..writeln('const List<Locale> kDashcnLocales = <Locale>[');
  for (final String code in sorted) {
    out.writeln('  ${localeConstructor(code)},');
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('/// Delegates for the installed locales (kit + widgets).')
    ..writeln(
      '/// Pass extra app delegates first; they win over the kit tables.',
    )
    ..writeln('List<LocalizationsDelegate<dynamic>> dashcnLocaleDelegates([')
    ..writeln(
      '  Iterable<LocalizationsDelegate<dynamic>> extra = const <LocalizationsDelegate<dynamic>>[],',
    )
    ..writeln(']) {')
    ..writeln('  return <LocalizationsDelegate<dynamic>[')
    ..writeln('    ...extra,')
    ..writeln('    ...DashcnLocalizations.localizationsDelegates,')
    ..writeln('    GlobalWidgetsLocalizations.delegate,')
    ..writeln('  ];')
    ..writeln('}');
  return out.toString();
}

/// Prints the shippable locale table; returns the process exit code.
int listLocales({
  required String kitRoot,
  required String projectDir,
  required void Function(String) out,
}) {
  final List<LocaleEntry> shippable = loadShippableLocales(kitRoot);
  final Set<String> installed = installedLocales(projectDir).toSet();
  out('CODE      DIR  TABLE                          INSTALLED');
  for (final LocaleEntry entry in shippable) {
    final String mark = installed.contains(entry.code) ? 'yes' : '';
    out(
      '${entry.code.padRight(9)} '
      '${entry.rtl ? 'RTL' : 'LTR'}  '
      'localizations_${entry.fileSuffix}.dart'
      '${mark.isEmpty ? '' : '  $mark'}',
    );
  }
  return 0;
}

/// Installs [code] into [projectDir]; returns the process exit code.
///
/// Writes `lib/dashcn_i18n.dart` (locale wiring, no pasting) and records
/// [code] in `dashcn_locales.json`. Re-adding is a byte-identical no-op.
int addLocale({
  required String kitRoot,
  required String projectDir,
  required String code,
  required void Function(String) out,
}) {
  final List<LocaleEntry> shippable = loadShippableLocales(kitRoot);
  if (!shippable.any((LocaleEntry e) => e.code == code)) {
    throw LocaleToolError(
      'unknown locale "$code"; run `locale list` for the shippable codes',
    );
  }
  if (!Directory(projectDir).existsSync()) {
    throw LocaleToolError('project dir "$projectDir" does not exist');
  }
  final List<String> installed = installedLocales(projectDir);
  final List<String> next =
      (installed.contains(code) ? installed : <String>[...installed, code])
        ..sort();
  _manifestFile(projectDir).writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(<String, Object>{'locales': next})}\n',
  );
  final File wiring = File('$projectDir/lib/dashcn_i18n.dart');
  wiring.parent.createSync(recursive: true);
  wiring.writeAsStringSync(renderWiringFile(next));
  out('locale $code installed (${next.length} total)');
  return 0;
}
